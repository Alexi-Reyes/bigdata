drop table if exists commande_promotion, promotion_categorie, promotion_produit,
  ligne_commande, ligne_panier, panier, prix_variante, variante, produit_categorie,
  produit, categorie, marque, commande, promotion, devise, adresse, compte cascade;

create table compte (
  id                 integer generated by default as identity primary key,
  nom                varchar(100) not null,
  prenom             varchar(100) not null,
  nom_affiche        varchar(50)  not null,
  email              varchar(255) not null unique,
  telephone          varchar(20),
  mot_de_passe       varchar(255) not null,
  date_creation      timestamptz  not null default now(),
  date_modification  timestamptz,
  est_actif          boolean      not null default true
);

create table adresse (
  id             integer generated by default as identity primary key,
  compte_id      integer      not null references compte(id) on delete cascade,
  type_adresse   varchar(20)  not null check (type_adresse in ('livraison', 'facturation')),
  rue            varchar(255) not null,
  complement     varchar(255),
  code_postal    varchar(10)  not null,
  ville          varchar(100) not null,
  pays           varchar(100) not null,
  par_defaut     boolean,
  date_creation  timestamptz  not null default now()
);

create table devise (
  id       integer generated by default as identity primary key,
  code     char(3)     not null unique,
  nom      varchar(50) not null,
  symbole  varchar(5)  not null
);

create table marque (
  id   integer generated by default as identity primary key,
  nom  varchar(100) not null unique
);

create table categorie (
  id                   integer generated by default as identity primary key,
  nom                  varchar(100) not null,
  categorie_parent_id  integer references categorie(id) on delete set null
);

create table produit (
  id             integer generated by default as identity primary key,
  nom            varchar(150) not null,
  description    text         not null,
  reference      varchar(50)  not null unique,
  est_actif      boolean      not null default true,
  marque_id      integer      not null references marque(id),
  date_creation  timestamptz  not null default now()
);

create table produit_categorie (
  produit_id    integer not null references produit(id)   on delete cascade,
  categorie_id  integer not null references categorie(id) on delete cascade,
  primary key (produit_id, categorie_id)
);

create table variante (
  id             integer generated by default as identity primary key,
  produit_id     integer     not null references produit(id) on delete cascade,
  reference      varchar(50) not null unique,
  taille         varchar(20),
  couleur        varchar(50),
  stock          integer     not null default 0 check (stock >= 0),
  date_creation  timestamptz not null default now()
);

create table prix_variante (
  id           integer generated by default as identity primary key,
  variante_id  integer       not null references variante(id) on delete cascade,
  devise_id    integer       not null references devise(id),
  prix         numeric(10,2) not null check (prix >= 0),
  date_debut   timestamptz   not null,
  date_fin     timestamptz,
  check (date_fin is null or date_fin > date_debut)
);

create table panier (
  id             integer generated by default as identity primary key,
  compte_id      integer     not null unique references compte(id) on delete cascade,
  date_creation  timestamptz not null default now()
);

create table ligne_panier (
  panier_id    integer not null references panier(id)   on delete cascade,
  variante_id  integer not null references variante(id) on delete cascade,
  quantite     integer not null check (quantite > 0),
  primary key (panier_id, variante_id)
);

create table promotion (
  id                   integer generated by default as identity primary key,
  nom                  varchar(100)  not null,
  code                 varchar(50)   unique,
  portee               varchar(20)   not null check (portee in ('panier', 'produit', 'categorie')),
  type_reduction       varchar(20)   not null check (type_reduction in ('pourcentage', 'montant')),
  valeur               numeric(10,2) not null check (valeur > 0),
  devise_id            integer       references devise(id),
  date_debut           timestamptz   not null,
  date_fin             timestamptz   not null,
  nb_max_utilisations  integer       check (nb_max_utilisations > 0),
  check (date_fin > date_debut),
  check (type_reduction <> 'pourcentage' or valeur <= 100)
);

create table promotion_produit (
  promotion_id  integer not null references promotion(id) on delete cascade,
  produit_id    integer not null references produit(id)   on delete cascade,
  primary key (promotion_id, produit_id)
);

create table promotion_categorie (
  promotion_id  integer not null references promotion(id) on delete cascade,
  categorie_id  integer not null references categorie(id) on delete cascade,
  primary key (promotion_id, categorie_id)
);

create table commande (
  id                     integer generated by default as identity primary key,
  compte_id              integer references compte(id) on delete set null,
  devise_id              integer      not null references devise(id),
  numero                 varchar(20)  not null unique,
  date_commande          timestamptz  not null default now(),
  etat                   varchar(20)  not null default 'en_attente'
                         check (etat in ('en_attente', 'payee', 'en_preparation', 'expediee', 'livree', 'annulee', 'remboursee')),
  frais_livraison        numeric(10,2) not null default 0 check (frais_livraison >= 0),
  email                  varchar(255) not null,
  nom                    varchar(100) not null,
  prenom                 varchar(100) not null,
  telephone              varchar(20),
  livraison_rue          varchar(255) not null,
  livraison_complement   varchar(255),
  livraison_code_postal  varchar(10)  not null,
  livraison_ville        varchar(100) not null,
  livraison_pays         varchar(100) not null
);

create table ligne_commande (
  commande_id    integer       not null references commande(id) on delete cascade,
  variante_id    integer       not null references variante(id),
  quantite       integer       not null check (quantite > 0),
  prix_unitaire  numeric(10,2) not null check (prix_unitaire >= 0),
  primary key (commande_id, variante_id)
);

create table commande_promotion (
  commande_id     integer       not null references commande(id)  on delete cascade,
  promotion_id    integer       not null references promotion(id),
  montant_remise  numeric(10,2) not null check (montant_remise >= 0),
  primary key (commande_id, promotion_id)
);
